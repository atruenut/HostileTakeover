static signed char gx0[95], gw[95];
static int ready;

static void font_init(void) {
    int i, j, b;
    for (i = 0; i < 95; i++) {
        int mn = 5, mx = -1;
        for (j = 0; j < glyphs[i].n; j++)
            for (b = 0; b < 5; b++)
                if (glyphs[i].r[j] & (16 >> b)) { if (b < mn) mn = b; if (b > mx) mx = b; }
        if (mx < 0) { gx0[i] = 0; gw[i] = 2; }
        else { gx0[i] = (signed char)mn; gw[i] = (signed char)(mx - mn + 1); }
    }
    ready = 1;
}

int font_advance(int ch) {
    int i;
    if (!ready) font_init();
    if (ch < 32 || ch > 126) ch = '?';
    i = ch - 32;
    return gw[i] + 1;
}

/* draw one glyph, scaled; returns advance in unscaled px */
int font_draw(int x, int y, int ch, int c, int sc) {
    int i, j, b;
    if (!ready) font_init();
    if (ch < 32 || ch > 126) ch = '?';
    i = ch - 32;
    for (j = 0; j < glyphs[i].n; j++) {
        unsigned char row = glyphs[i].r[j];
        if (!row) continue;
        for (b = 0; b < 5; b++) {
            if (row & (16 >> b)) {
                int px = x + (b - gx0[i]) * sc, py = y + (glyphs[i].top + j) * sc;
                if (sc == 1) gfx_pixel(px, py, c); else gfx_rect(px, py, sc, sc, c);
            }
        }
    }
    return gw[i] + 1;
}
